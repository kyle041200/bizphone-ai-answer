"""Booklet-matched deliverable descriptions for the eight existing Marketing cards."""
import re
import unittest
from pathlib import Path


class MarketingDeliverableDescriptions(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        source = (Path(__file__).parents[1] / "src/routes/marketing.tsx").read_text()
        block = source.split("const popular = [", 1)[1].split("] as const;", 1)[0]
        pairs = re.findall(r'title: "([^"]+)", body: "([^"]+)"', block)
        cls.bodies = {title: body for title, body in pairs}

    def test_landing_page(self):
        self.assertEqual(self.bodies["Landing Page"],
            "A full landing page with copy, design, and development with 1–2 calls-to-action.")

    def test_downloadable_lead_magnet(self):
        self.assertEqual(self.bodies["Lead Magnet"],
            "A downloadable PDF or guide up to 5 pages designed to attract leads, deliver value, and support conversions.")

    def test_written_and_setup_email_sequence(self):
        self.assertEqual(self.bodies["Email Nurture Sequence"],
            "10 compelling emails written, plus configuration of the approved email sequence inside your email or CRM platform, including timing, basic segmentation, and testing.")

    def test_signature_social_pack(self):
        self.assertEqual(self.bodies["Social Content Pack"],
            "Up to 10 custom social media posts designed to match your brand.")

    def test_ai_article_human_edited(self):
        self.assertEqual(self.bodies["SEO Article"],
            "500 words of a ghost-written and edited article that showcases your expertise, mostly generated by AI but edited by a human.")

    def test_google_business_profile(self):
        self.assertEqual(self.bodies["Google Business Profile"],
            "Setup and optimization of your Google Business Profile, including profile creation or refresh, business description, cover image, contact info setup, and basic branding alignment.")

    def test_brand_refresh(self):
        self.assertEqual(self.bodies["Brand Refresh"],
            "A modernization of existing brand assets, such as logo refinements, updated colors and fonts, a simple style guide, and refreshed supporting materials while preserving the core identity of your business.")

    def test_signature_website(self):
        self.assertEqual(self.bodies["Website"],
            "A fully designed and developed website up to 5 pages including professional copy and visual design. This includes domain connection and SSL certification.")


if __name__ == "__main__":
    unittest.main()
